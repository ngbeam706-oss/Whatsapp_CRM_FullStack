-- Ads conversion analytics, phase A2 (docs/progress/ads-module.md "Funnel"):
--   1. lead_status_history: every status change of a lead (from / to key and TYPE, when, by whom, how), written by the
--      server wherever a status changes (staff, bot, Add lead, moving chats when a status is removed). Used for
--      "time to convert" and the daily trend. History starts on the day this is run.
--   2. whatsapp_leads.booking_value: an optional amount for a booking (asked when a chat moves to a Booked / Done
--      kind of status); empty = the business's average from "Bookings to Meta". Used for revenue and return on ad spend.
-- Server-only. Safe to re-run.

create table if not exists public.lead_status_history (
  id           bigint generated by default as identity primary key,
  business_id  uuid not null references public.businesses(id) on delete cascade,
  phone        text not null,
  from_key     text,
  from_type    text check (from_type is null or from_type in ('new', 'working', 'won', 'done', 'repeat', 'lost')),
  to_key       text not null,
  to_type      text not null check (to_type in ('new', 'working', 'won', 'done', 'repeat', 'lost')),
  changed_by   text,                          -- staff email, or 'bot'
  source       text not null default 'staff' check (source in ('staff', 'bot', 'added', 'bulk')),
  changed_at   timestamptz not null default now()
);
create index if not exists lead_status_history_business_idx on public.lead_status_history (business_id, changed_at desc);
create index if not exists lead_status_history_lead_idx on public.lead_status_history (business_id, phone, changed_at);
alter table public.lead_status_history enable row level security;
revoke all on public.lead_status_history from anon, authenticated;

alter table public.whatsapp_leads add column if not exists booking_value numeric(12, 2);
alter table public.whatsapp_leads drop constraint if exists whatsapp_leads_booking_value_check;
alter table public.whatsapp_leads add constraint whatsapp_leads_booking_value_check
  check (booking_value is null or (booking_value >= 0 and booking_value <= 100000000));

