-- =====================================================================
-- Admin console (monitoring): system event log, worker runs, per-business health.
--
-- Run once in Supabase -> SQL Editor (after 20261114_ads_c_controls.sql),
-- BEFORE deploying the matching app update. Safe to re-run.
--
-- All three tables are SERVER-ONLY (RLS on, no policies, no browser grants), like
-- business_whatsapp: business staff cannot read them, and the Platform Admin reads them
-- only through the server (/api/platform), which returns counts, codes and short error
-- text. They never hold message bodies, phone numbers or tokens (the server scrubs them).
-- =====================================================================

-- 1. System events: errors and warnings from the webhook, worker, Meta, AI, ads, auth -----
create table if not exists public.system_events (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  level        text not null check (level in ('info', 'warn', 'error', 'critical')),
  source       text not null check (source in ('webhook', 'worker', 'meta', 'ai', 'ads', 'auth', 'billing', 'system')),
  business_id  uuid references public.businesses(id) on delete set null,
  code         text check (code is null or char_length(code) <= 60),
  message      text not null default '' check (char_length(message) <= 500),
  count        int not null default 1 check (count >= 1),  -- same event repeated (throttled) within a minute
  details      jsonb not null default '{}'::jsonb
);
create index if not exists system_events_created_idx  on public.system_events (created_at desc);
create index if not exists system_events_business_idx on public.system_events (business_id, created_at desc);
create index if not exists system_events_source_idx   on public.system_events (source, level, created_at desc);

alter table public.system_events enable row level security;
revoke all on public.system_events from anon, authenticated;

-- 2. Worker runs: one row per run of the scheduled worker ------------------------------
create table if not exists public.worker_runs (
  id           bigint generated by default as identity primary key,
  started_at   timestamptz not null,
  finished_at  timestamptz,
  duration_ms  int,
  ok           boolean not null default true,
  steps        jsonb not null default '{}'::jsonb,   -- step -> counts / ms, e.g. {"campaigns": {"sent": 12}}
  error_count  int not null default 0,
  errors       jsonb not null default '[]'::jsonb    -- [{ step, message }] (scrubbed, short)
);
create index if not exists worker_runs_started_idx on public.worker_runs (started_at desc);

alter table public.worker_runs enable row level security;
revoke all on public.worker_runs from anon, authenticated;

-- 3. Per-business health: last webhook, last signature failure, WhatsApp number quality ----
create table if not exists public.business_health (
  business_id             uuid primary key references public.businesses(id) on delete cascade,
  last_webhook_at         timestamptz,
  last_signature_fail_at  timestamptz,
  wa_quality_rating       text,
  wa_messaging_tier       text,
  wa_checked_at           timestamptz,
  wa_check_error          text check (wa_check_error is null or char_length(wa_check_error) <= 300),
  updated_at              timestamptz not null default now()
);

alter table public.business_health enable row level security;
revoke all on public.business_health from anon, authenticated;

-- Check:
select (select count(*) from public.system_events) as events,
       (select count(*) from public.worker_runs)   as worker_runs,
       (select count(*) from public.business_health) as health_rows;
