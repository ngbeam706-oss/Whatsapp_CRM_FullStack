-- 1. What customers did (written by the bot / webhook) ---------------------
create table if not exists public.contact_events (
  id          bigint generated by default as identity primary key,
  phone       text not null,
  event_type  text not null,          -- order_enquiry | item_viewed | new_contact
  data        jsonb not null default '{}'::jsonb,   -- e.g. {"itemId":"kit_lean_well","item":"Lean Well (28 Days)","isKit":true}
  created_at  timestamptz not null default now()
);
create index if not exists contact_events_phone_idx on public.contact_events (phone, event_type, created_at desc);

-- 2. Automation rules -----------------------------------------------------
create table if not exists public.automations (
  id                 uuid primary key default gen_random_uuid(),
  name               text not null,
  is_active          boolean not null default true,
  trigger            text not null
                     check (trigger in ('order_enquiry', 'kit_order', 'item_viewed', 'new_contact', 'inactive')),
  delay_minutes      int not null check (delay_minutes between 0 and 525600),  -- up to 1 year
  stop_if_replied    boolean not null default true,
  stop_if_ordered    boolean not null default false,
  template_name      text not null,
  template_language  text not null,
  template_category  text,
  variables          jsonb not null default '{}'::jsonb,   -- same shape as campaigns.variables (+ template snapshot)
  last_scan_at       timestamptz,     -- for 'inactive' rules: when contacts were last checked
  created_by         text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

-- 3. Scheduled / sent follow-up messages ------------------------------------
create table if not exists public.automation_runs (
  id             bigint generated by default as identity primary key,
  automation_id  uuid not null references public.automations(id) on delete cascade,
  phone          text not null,
  name           text,
  event_id       bigint references public.contact_events(id) on delete set null,
  data           jsonb not null default '{}'::jsonb,   -- copied from the event (item name...)
  due_at         timestamptz not null,
  status         text not null default 'scheduled'
                 check (status in ('scheduled', 'sending', 'sent', 'delivered', 'read', 'failed', 'cancelled', 'skipped')),
  reason         text,             -- why cancelled / skipped / failed
  wamid          text,
  attempts       int not null default 0,
  claimed_at     timestamptz,
  created_at     timestamptz not null default now(),
  sent_at        timestamptz,
  delivered_at   timestamptz,
  read_at        timestamptz,
  replied_at     timestamptz
);

-- At most one pending follow-up per rule per customer (no double messages).
create unique index if not exists automation_runs_one_pending_idx
  on public.automation_runs (automation_id, phone) where status in ('scheduled', 'sending');
create index if not exists automation_runs_due_idx on public.automation_runs (status, due_at);
create unique index if not exists automation_runs_wamid_idx on public.automation_runs (wamid) where wamid is not null;
create index if not exists automation_runs_phone_idx on public.automation_runs (phone, sent_at desc);
create index if not exists automation_runs_auto_idx on public.automation_runs (automation_id, created_at desc);

-- 4. Per-automation counts -----------------------------------------------
create or replace view public.automation_stats
with (security_invoker = true) as
select
  a.id as automation_id,
  count(r.id) filter (where r.status in ('scheduled', 'sending'))          as scheduled,
  count(r.id) filter (where r.status in ('sent', 'delivered', 'read'))     as sent,
  count(r.id) filter (where r.status in ('delivered', 'read'))             as delivered,
  count(r.id) filter (where r.status = 'read')                             as read,
  count(r.id) filter (where r.replied_at is not null)                      as replied,
  count(r.id) filter (where r.status = 'cancelled')                        as cancelled,
  count(r.id) filter (where r.status in ('failed', 'skipped'))             as failed
from public.automations a
left join public.automation_runs r on r.automation_id = a.id
group by a.id;

-- 5. Safe claiming of due follow-ups (server only) -------------------------
create or replace function public.claim_due_automation_runs(batch_size int default 50)
returns setof public.automation_runs
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  update public.automation_runs r
     set status = 'sending', claimed_at = now(), attempts = r.attempts + 1
   where r.id in (
     select r2.id
       from public.automation_runs r2
       join public.automations a on a.id = r2.automation_id
      where a.is_active
        and r2.attempts < 3
        and r2.due_at <= now()
        and (r2.status = 'scheduled'
             or (r2.status = 'sending' and r2.claimed_at < now() - interval '10 minutes'))
      order by r2.due_at
      limit greatest(1, least(batch_size, 200))
      for update of r2 skip locked
   )
  returning r.*;
end;
$$;

revoke all on function public.claim_due_automation_runs(int) from public, anon, authenticated;
grant execute on function public.claim_due_automation_runs(int) to service_role;

-- 6. Row Level Security: staff only --------------------------------------
alter table public.contact_events  enable row level security;
alter table public.automations     enable row level security;
alter table public.automation_runs enable row level security;

drop policy if exists "staff full access" on public.contact_events;
drop policy if exists "staff full access" on public.automations;
drop policy if exists "staff full access" on public.automation_runs;
create policy "staff full access" on public.contact_events
  for all to authenticated using (public.is_staff()) with check (public.is_staff());
create policy "staff full access" on public.automations
  for all to authenticated using (public.is_staff()) with check (public.is_staff());
create policy "staff full access" on public.automation_runs
  for all to authenticated using (public.is_staff()) with check (public.is_staff());

revoke all on public.contact_events, public.automations, public.automation_runs, public.automation_stats from anon;

