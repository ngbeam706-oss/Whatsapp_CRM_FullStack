-- 2. Campaigns ------------------------------------------------------------
create table if not exists public.campaigns (
  id                 uuid primary key default gen_random_uuid(),
  name               text not null,
  template_name      text not null,
  template_language  text not null,
  template_category  text,
  -- How to fill template variables, e.g. {"body": [{"type":"contact_name"}, {"type":"text","value":"20% off"}]}
  variables          jsonb not null default '{}'::jsonb,
  -- Audience filter used to build the recipient list, kept for reference.
  segment            jsonb not null default '{}'::jsonb,
  status             text not null default 'draft'
                     check (status in ('draft', 'sending', 'completed', 'cancelled')),
  created_by         text,
  created_at         timestamptz not null default now(),
  started_at         timestamptz,
  completed_at       timestamptz
);

create table if not exists public.campaign_recipients (
  id            bigint generated by default as identity primary key,
  campaign_id   uuid not null references public.campaigns(id) on delete cascade,
  phone         text not null,
  name          text,
  status        text not null default 'queued'
                check (status in ('queued', 'sending', 'sent', 'delivered', 'read', 'failed', 'skipped')),
  wamid         text,           -- WhatsApp message id returned by Meta
  error         text,
  attempts      int not null default 0,
  claimed_at    timestamptz,
  sent_at       timestamptz,
  delivered_at  timestamptz,
  read_at       timestamptz,
  replied_at    timestamptz,
  unique (campaign_id, phone)
);

create index if not exists campaign_recipients_queue_idx on public.campaign_recipients (status, campaign_id);
create unique index if not exists campaign_recipients_wamid_idx on public.campaign_recipients (wamid) where wamid is not null;
create index if not exists campaign_recipients_phone_idx on public.campaign_recipients (phone, sent_at desc);

-- 3. Per-campaign counts ----------------------------------------------------
-- "delivered" includes read; "sent" includes delivered and read.
create or replace view public.campaign_stats
with (security_invoker = true) as
select
  c.id as campaign_id,
  count(r.id)                                                                as total,
  count(r.id) filter (where r.status in ('queued', 'sending'))               as pending,
  count(r.id) filter (where r.status in ('sent', 'delivered', 'read'))       as sent,
  count(r.id) filter (where r.status in ('delivered', 'read'))               as delivered,
  count(r.id) filter (where r.status = 'read')                               as read,
  count(r.id) filter (where r.replied_at is not null)                        as replied,
  count(r.id) filter (where r.status = 'failed')                             as failed,
  count(r.id) filter (where r.status = 'skipped')                            as skipped
from public.campaigns c
left join public.campaign_recipients r on r.campaign_id = c.id
group by c.id;

-- 4. Safe batch claiming for the sender ---------------------------------
-- Marks up to batch_size queued recipients of running campaigns as 'sending'
-- and returns them. SKIP LOCKED means two senders running at once never get
-- the same row, so nobody is messaged twice. Rows stuck in 'sending' for more
-- than 10 minutes (a crashed sender) are retried, at most 3 attempts.
create or replace function public.claim_campaign_recipients(batch_size int default 50)
returns setof public.campaign_recipients
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  update public.campaign_recipients r
     set status = 'sending', claimed_at = now(), attempts = r.attempts + 1
   where r.id in (
     select r2.id
       from public.campaign_recipients r2
       join public.campaigns c on c.id = r2.campaign_id
      where c.status = 'sending'
        and r2.attempts < 3
        and (r2.status = 'queued'
             or (r2.status = 'sending' and r2.claimed_at < now() - interval '10 minutes'))
      order by r2.id
      limit greatest(1, least(batch_size, 200))
      for update of r2 skip locked
   )
  returning r.*;
end;
$$;

-- Only the server (service key) may claim batches.
revoke all on function public.claim_campaign_recipients(int) from public, anon, authenticated;
grant execute on function public.claim_campaign_recipients(int) to service_role;

-- 5. Row Level Security: staff only ------------------------------------
alter table public.campaigns enable row level security;
alter table public.campaign_recipients enable row level security;

drop policy if exists "staff full access" on public.campaigns;
drop policy if exists "staff full access" on public.campaign_recipients;
create policy "staff full access" on public.campaigns
  for all to authenticated using (public.is_staff()) with check (public.is_staff());
create policy "staff full access" on public.campaign_recipients
  for all to authenticated using (public.is_staff()) with check (public.is_staff());

revoke all on public.campaigns, public.campaign_recipients, public.campaign_stats from anon;

