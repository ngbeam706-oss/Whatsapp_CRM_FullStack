-- 1. Contact (lead) fields for the inbox and pipeline -----------------------
alter table public.whatsapp_leads add column if not exists assigned_to      text;          -- staff email
alter table public.whatsapp_leads add column if not exists stage            text;
alter table public.whatsapp_leads add column if not exists stage_changed_at timestamptz;
alter table public.whatsapp_leads add column if not exists bot_paused       boolean not null default false;
alter table public.whatsapp_leads add column if not exists bot_paused_until timestamptz;   -- null = until resumed
alter table public.whatsapp_leads add column if not exists unread_count     int not null default 0;
alter table public.whatsapp_leads add column if not exists last_inbound_at  timestamptz;   -- for WhatsApp's 24-hour reply window

-- Pipeline stages. Drop any older rule, map older values to the new set, then add the rule.
alter table public.whatsapp_leads drop constraint if exists whatsapp_leads_stage_check;
update public.whatsapp_leads set stage = case stage
    when 'engaged'  then 'interested'
    when 'quoted'   then 'interested'
    when 'customer' then 'ordered'
    when 'inactive' then 'lost'
    else 'new'
  end
where stage is null or stage not in ('new', 'interested', 'ordered', 'repeat', 'lost');
alter table public.whatsapp_leads alter column stage set default 'new';
alter table public.whatsapp_leads alter column stage set not null;
alter table public.whatsapp_leads add constraint whatsapp_leads_stage_check
  check (stage in ('new', 'interested', 'ordered', 'repeat', 'lost'));

create index if not exists whatsapp_leads_assigned_idx on public.whatsapp_leads (assigned_to, last_contacted_at desc);
create index if not exists whatsapp_leads_stage_idx    on public.whatsapp_leads (stage, last_contacted_at desc);
create index if not exists whatsapp_leads_recent_idx   on public.whatsapp_leads (last_contacted_at desc);

-- 2. Messages: one row per WhatsApp message, linked to the contact ---------
alter table public.whatsapp_messages add column if not exists contact_phone   text;
alter table public.whatsapp_messages add column if not exists sent_by         text;   -- staff email for manual replies
alter table public.whatsapp_messages add column if not exists delivery_status text;   -- sent / delivered / read / failed
alter table public.whatsapp_messages add column if not exists audio_url       text;   -- call recordings

update public.whatsapp_messages
   set contact_phone = case when direction = 'inbound' then sender else recipient end
 where contact_phone is null;

-- The old dashboard saved every message again from the browser, creating
-- exact duplicates. Keep the first copy of each WhatsApp message id.
delete from public.whatsapp_messages a
 using public.whatsapp_messages b
 where a.message_id is not null
   and a.message_id = b.message_id
   and a.id > b.id;

create unique index if not exists whatsapp_messages_message_id_key on public.whatsapp_messages (message_id);
create index if not exists whatsapp_messages_contact_idx on public.whatsapp_messages (contact_phone, "timestamp" desc);

-- 3. Notes on a contact -----------------------------------------------------
create table if not exists public.lead_notes (
  id          bigint generated by default as identity primary key,
  phone       text not null,
  author      text not null,
  body        text not null check (char_length(body) between 1 and 2000),
  created_at  timestamptz not null default now()
);
create index if not exists lead_notes_phone_idx on public.lead_notes (phone, created_at desc);

-- 4. Server helpers (service key only) ----------------------------------------

-- Count a new incoming message: unread +1 and open the 24-hour reply window.
create or replace function public.lead_mark_inbound(p_phone text)
returns void
language sql
security definer
set search_path = public
as $$
  update public.whatsapp_leads
     set unread_count = unread_count + 1,
         last_inbound_at = now()
   where phone = p_phone;
$$;

-- Add an existing login (by email) to the staff list. Used by the Team page
-- when the person already has an account.
create or replace function public.staff_add_existing(p_email text, p_role text)
returns setof public.staff_members
language sql
security definer
set search_path = public
as $$
  insert into public.staff_members (user_id, email, role)
  select id, email, p_role from auth.users where lower(email) = lower(p_email)
  on conflict (user_id) do update set role = excluded.role
  returning *;
$$;

revoke all on function public.lead_mark_inbound(text) from public, anon, authenticated;
revoke all on function public.staff_add_existing(text, text) from public, anon, authenticated;
grant execute on function public.lead_mark_inbound(text) to service_role;
grant execute on function public.staff_add_existing(text, text) to service_role;

-- 5. Row Level Security -------------------------------------------------------
alter table public.lead_notes enable row level security;
drop policy if exists "staff full access" on public.lead_notes;
create policy "staff full access" on public.lead_notes
  for all to authenticated using (public.is_staff()) with check (public.is_staff());
revoke all on public.lead_notes from anon;

