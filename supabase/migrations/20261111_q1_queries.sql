-- =====================================================================
-- Q1: Queries — raised by customers, by staff (to managers / the Business Admin),
-- and to Platform support. Tables, numbering and access rules.
--
-- Run once in Supabase -> SQL Editor (after all earlier files). Safe to re-run.
-- Nothing in the live app uses these tables until the Q2–Q4 update is deployed.
--
-- Writing is done ONLY by the server (secret key). Browser logins may only READ,
-- and only what their role allows:
--   * Customer queries: every staff member of the business can see them.
--   * Team (internal) queries: the person who raised it; managers if it was sent to
--     "Managers"; the Business Admin always.
--   * Platform support queries: the Platform Admin, the person who raised it and their
--     Business Admin.
--   * The Platform Admin can NEVER read customer or team queries (or chats).
-- =====================================================================

