// In-memory Postgres (PGlite) with just enough of Supabase's setup (roles, auth.uid(),
// storage.objects, default grants and the four original tables) to run our migrations
// and check the database rules (RLS) for real.
const fs = require('fs');
const path = require('path');

const MIGRATIONS = path.join(__dirname, '..', '..', 'supabase', 'migrations');

const SUPABASE_STUB = `
create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;
grant usage on schema public to anon, authenticated, service_role;
alter default privileges in schema public grant all on tables    to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema public grant execute on functions to anon, authenticated, service_role;

create schema auth;
create table auth.users (id uuid primary key default gen_random_uuid(), email text not null);
create function auth.uid() returns uuid language sql stable
  as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant usage on schema auth to anon, authenticated, service_role;
grant execute on function auth.uid() to public;

create schema storage;
create table storage.objects (id uuid primary key default gen_random_uuid(), bucket_id text);

-- The tables that existed before our migrations (same columns as the live project).
create table public.whatsapp_leads (
  id bigint generated by default as identity primary key, phone text unique, name text,
  last_message text, status text, last_contacted_at timestamptz, created_at timestamptz default now(), referral jsonb);
create table public.whatsapp_messages (
  id bigint generated by default as identity primary key, message_id text, direction text, sender text,
  sender_name text, recipient text, body text, type text, "timestamp" timestamptz default now());
create table public.whatsapp_bot_rules (
  id text primary key, keyword text, match_type text, response_type text, response_text text,
  buttons jsonb, is_active boolean, updated_at timestamptz);
create table public.whatsapp_catalog (id text primary key, data jsonb, updated_at timestamptz);
`;

/** Fresh database with every migration applied (files in name order). */
async function freshDb({ upTo } = {}) {
  const { PGlite } = await import('@electric-sql/pglite');
  const db = new PGlite();
  await db.exec(SUPABASE_STUB);
  const files = fs.readdirSync(MIGRATIONS).filter(f => f.endsWith('.sql')).sort();
  for (const f of files) {
    if (upTo && f > upTo) break;
    await db.exec(fs.readFileSync(path.join(MIGRATIONS, f), 'utf8'));
  }
  return db;
}

function migrationSql(name) {
  return fs.readFileSync(path.join(MIGRATIONS, name), 'utf8');
}

/** Run fn with the database acting as a signed-in browser user (RLS applies). */
async function asUser(db, userId, fn) {
  await db.query("select set_config('request.jwt.claim.sub', $1, false)", [userId || '']);
  await db.exec('set role authenticated');
  try {
    return await fn();
  } finally {
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claim.sub', '', false)");
  }
}

module.exports = { freshDb, migrationSql, asUser };
