-- Ads phase E1: bookings back to Meta (Conversions API for business messaging). Safe to re-run; only adds.
--   ad_conversion_settings: per business, off by default; optional average booking value.
--   ad_conversion_datasets: Meta's dataset id per WhatsApp Business Account (created on first use).
--   ad_conversions: the queue of events (one per lead + ad click + event), sent by the worker.
-- All server-only (no browser access).

create table if not exists public.ad_conversion_settings (
  business_id    uuid primary key references public.businesses(id) on delete cascade,
  enabled        boolean not null default false,
  booking_value  numeric(12,2) check (booking_value is null or booking_value > 0),
  currency       text not null default 'INR' check (currency ~ '^[A-Z]{3}$'),
  updated_by     text,
  updated_at     timestamptz not null default now()
);
alter table public.ad_conversion_settings enable row level security;
revoke all on public.ad_conversion_settings from anon, authenticated;

create table if not exists public.ad_conversion_datasets (
  business_id  uuid not null references public.businesses(id) on delete cascade,
  waba_id      text not null check (waba_id ~ '^\d{5,30}$'),
  dataset_id   text not null check (dataset_id ~ '^\d{5,30}$'),
  created_at   timestamptz not null default now(),
  primary key (business_id, waba_id)
);
alter table public.ad_conversion_datasets enable row level security;
revoke all on public.ad_conversion_datasets from anon, authenticated;

create table if not exists public.ad_conversions (
  id           bigint generated by default as identity primary key,
  business_id  uuid not null references public.businesses(id) on delete cascade,
  phone        text not null,
  ctwa_clid    text not null check (char_length(ctwa_clid) between 4 and 500),
  event_name   text not null check (event_name in ('Purchase', 'LeadSubmitted')),
  stage        text not null,
  value        numeric(12,2),
  currency     text,
  status       text not null default 'pending' check (status in ('pending', 'sent', 'failed')),
  attempts     int not null default 0,
  error        text,
  event_time   timestamptz not null default now(),
  created_at   timestamptz not null default now(),
  sent_at      timestamptz,
  -- Meta does not deduplicate: one event per lead, ad click and event name.
  unique (business_id, phone, ctwa_clid, event_name)
);
create index if not exists ad_conversions_pending_idx on public.ad_conversions (status, created_at) where status = 'pending';
create index if not exists ad_conversions_business_idx on public.ad_conversions (business_id, created_at desc);
alter table public.ad_conversions enable row level security;
revoke all on public.ad_conversions from anon, authenticated;
