const test = require('node:test');
const assert = require('node:assert');
const { aiReplyMessages, AI_STAFF_BUTTON, AI_MENU_BUTTON } = require('../server/bot.cjs');
const { RAISE_BUTTON } = require('../server/queryBot.cjs');
const { flowText, systemPrompt } = require('../server/ai.cjs');

test('an AI answer goes out with the AI footer, "Main menu", "Raise a query" and "Connect with staff"', () => {
  const msgs = aiReplyMessages('We have millet dosa batter, 1 kg.');
  assert.equal(msgs.length, 1);
  assert.equal(msgs[0].kind, 'buttons');
  assert.equal(msgs[0].body, 'We have millet dosa batter, 1 kg.');
  assert.match(msgs[0].footer, /generated by our AI assistant/);
  assert.ok(msgs[0].footer.length <= 60);
  assert.deepEqual(msgs[0].buttons, [AI_MENU_BUTTON, RAISE_BUTTON, AI_STAFF_BUTTON]);
});

test('the AI buttons fit WhatsApp limits and the staff one reuses the handover id', () => {
  assert.equal(AI_STAFF_BUTTON.id, 'btn_talk_staff');
  for (const b of [AI_MENU_BUTTON, RAISE_BUTTON, AI_STAFF_BUTTON]) assert.ok(b.title.length <= 20);
  assert.notEqual(AI_MENU_BUTTON.id, AI_STAFF_BUTTON.id);
});

test('a very long answer is sent as text, then a short button message', () => {
  const long = 'a'.repeat(1500);
  const msgs = aiReplyMessages(long);
  assert.deepEqual(msgs.map(m => m.kind), ['text', 'buttons']);
  assert.equal(msgs[0].body, long);
  assert.ok(msgs[1].body.length <= 1024);
  assert.deepEqual(msgs[1].buttons, [AI_MENU_BUTTON, RAISE_BUTTON, AI_STAFF_BUTTON]);
});

const catalog = {
  welcomeMessage: 'Welcome to *Arogya Ruchulu*!',
  welcomeButtons: [{ id: 'btn_cat_rte', title: '🍱 Ready to Eat (RTE)' }],
  orderConfirmReply: 'Order enquiry received.',
  staffNotificationReply: 'Our team will message you shortly.',
};
const rules = [
  { keyword: 'price', responseText: 'Thali ₹130/meal', isActive: true, buttons: [{ id: 'b1', title: '🍱 Daily Meal Box' }] },
  { keyword: 'old', responseText: 'switched off rule', isActive: false },
];

test('the AI is given the keyword replies and flow messages (active rules only)', () => {
  const t = flowText(catalog, rules);
  assert.match(t, /"price", we reply: Thali ₹130\/meal \(menu options: Daily Meal Box\)/);
  assert.doesNotMatch(t, /switched off rule/);
  assert.match(t, /Welcome message: Welcome to \*Arogya Ruchulu\*!/);
  assert.match(t, /After an order enquiry: Order enquiry received\./);
  assert.match(t, /Main menu options: Ready to Eat \(RTE\)/);
});

test('the system prompt includes the flow knowledge and points to the Main menu button', () => {
  const p = systemPrompt(catalog, { knowledge: 'We deliver daily.' }, rules);
  assert.match(p, /Our standard replies \(keyword rules\)/);
  assert.match(p, /tap \*Main menu\*/);
  assert.match(p, /We deliver daily\./);
});
