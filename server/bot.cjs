/** A catalog list (kits, dishes) as an array, even when it is missing. @param {unknown} list @returns {CatalogItem[]} */
const items = (list) => (Array.isArray(list) ? list : []);

/**
 * Whole-word / whole-phrase match, so "which" doesn't count as "hi" and "orate" isn't "rate".
 * @param {unknown} text @param {unknown} phrase
 */
function hasWord(text, phrase) {
  const p = String(phrase || '').trim().toLowerCase();
  if (!p) return false;
  const esc = p.replace(/[.*+?^${}()|[\]\\]/g, (ch) => `\\${ch}`);
  // Plurals for real words ("kits", "prices", "batters"), but not for "hi" (-> "his").
  const word = p.length >= 3 && /\p{L}$/u.test(p) ? `${esc}(?:s|es)?` : esc;
  return new RegExp(`(^|[^\\p{L}\\p{N}])${word}($|[^\\p{L}\\p{N}])`, 'u').test(String(text || '').toLowerCase());
}

// The basic flow every business has (defaults.cjs NEUTRAL_CATALOG): "Our services" opens the
// business's own list (catalog.menuItems); a row opens the item; "Book / Enquire" confirms.
const MENU_BUTTON_ID = 'btn_menu';
const STAFF_ROW_ID = 'row_talk_staff';
const TALK_STAFF_BUTTON = { id: 'btn_talk_staff', title: '💬 Talk to our team' };
const LIST_MAX_ROWS = 10; // Meta's limit for one interactive list

/**
 * The welcome menu buttons. "Our services" is left out while the business has no items in it,
 * so customers never open an empty list.
 * @param {Catalog} catalog
 * @returns {Button[]}
 */
function welcomeButtons(catalog) {
  const list = Array.isArray(catalog.welcomeButtons) && catalog.welcomeButtons.length ? catalog.welcomeButtons : DEFAULT_CATALOG.welcomeButtons;
  const hasMenu = items(catalog.menuItems).length > 0;
  const shown = list.filter((/** @type {any} */ b) => b && b.id && b.title && (b.id !== MENU_BUTTON_ID || hasMenu)).slice(0, 3);
  return shown.length ? shown : [TALK_STAFF_BUTTON];
}

/** What the customer sees after picking a menu item. @param {CatalogItem} item */
function menuItemDetails(item) {
  if (item.details && String(item.details).trim()) return String(item.details);
  const price = Number(item.price) > 0 ? `\nPrice: ₹${item.price}` : '';
  const desc = item.description ? `\n${item.description}` : '';
  return `*${item.title || 'Selected option'}*${price}${desc}\n\nWould you like to book or enquire?`;
}

const AI_SENDER = 'AI Assistant ✨';
// Every AI answer says it came from the AI and offers a person. The button reuses the
// "talk to staff" id, so tapping it sends the team-notified message and pauses the bot + AI.
const AI_FOOTER = '🤖 This reply was generated by our AI assistant';
const AI_STAFF_BUTTON = { id: 'btn_talk_staff', title: 'Connect with staff' };
// With the AI on, typed words like "menu" reach the AI, so each answer also offers the button menu.
const AI_MENU_BUTTON = { id: 'btn_ai_menu', title: 'Main menu' };
// Customers can raise a query from any AI answer too (WhatsApp allows 3 buttons).
const queryBot = require('./queryBot.cjs');
const AI_BUTTONS = [AI_MENU_BUTTON, queryBot.RAISE_BUTTON, AI_STAFF_BUTTON];
const BUTTON_BODY_MAX = 1024; // Meta's limit for an interactive message body

/**
 * How to send one AI answer: a button message (answer + AI footer + "Connect with staff").
 * An answer too long for a button message goes as plain text first, then a short button message.
 * @param {unknown} reply @returns {AiMessage[]}
 */
function aiReplyMessages(reply) {
  const text = String(reply || '').trim();
  if (text.length <= BUTTON_BODY_MAX) {
    return [{ kind: 'buttons', body: text, footer: AI_FOOTER, buttons: AI_BUTTONS }];
  }
  return [
    { kind: 'text', body: text },
    { kind: 'buttons', body: 'Need more help? Our team is here for you.', footer: AI_FOOTER, buttons: AI_BUTTONS },
  ];
}

/** @param {any} wa @param {string} customerNumber @param {string} reply */
async function sendAiReply(wa, customerNumber, reply) {
  /** @type {MetaSendResult | undefined} */
  let last;
  for (const m of aiReplyMessages(reply)) {
    last = m.kind === 'text'
      ? await sendTextMessage(wa, customerNumber, m.body)
      : await sendInteractiveButtons(wa, customerNumber, m.body, m.buttons, { footer: m.footer });
    if (last?.error) return last;
  }
  return last;
}

/**
 * Ask Claude to answer. Returns true if the customer got a reply (an answer or a handover).
 * @param {string} biz @param {string} customerNumber @param {Catalog} catalog
 */
async function tryAiAnswer(biz, customerNumber, catalog) {
  const wa = await whatsappFor(biz, customerNumber);
  if (!wa) return false;
  let result;
  try {
    result = await ai.answerCustomer({ businessId: biz, phone: cleanPhone(customerNumber), catalog });
  } catch (err) {
    console.error('[AI] answer failed:', err);
    return false;
  }
  if (result.reply) {
    const sentResp = await sendAiReply(wa, customerNumber, result.reply);
    // Shown in the inbox as plain text, with the footer and button noted underneath.
    await recordBotAction(biz, customerNumber, `${result.reply}\n\n_${AI_FOOTER}_ · ${AI_BUTTONS.map(b => `[${b.title}]`).join(' ')}`, 'text', sentResp, AI_SENDER);
    await dbRequest('contact_events', { method: 'POST', prefer: 'return=minimal', body: { business_id: biz, phone: cleanPhone(customerNumber), event_type: 'ai_reply', data: {} } });
    await require('./limits.cjs').addUsage(biz, 'aiReplies', 1);
    return true;
  }
  if (result.handover) {
    const phone = cleanPhone(customerNumber);
    // The handover becomes a customer query, so it is tracked until solved; the customer gets its number.
    let ref = '';
    try {
      const q = await require('./queries.cjs').createQuery(biz, {
        kind: 'customer', contactPhone: phone, subject: `Handed over by the AI: ${String(result.reason || 'needs a person').slice(0, 90)}`,
        description: result.reason || null, notifyCustomer: false,
      }, { source: 'ai' });
      if (q.query) ref = `\n\nYour reference: *${q.query.ref}*`;
    } catch (err) { console.error('[Queries] AI handover query failed:', err instanceof Error ? err.message : err); }
    const text = (catalog.staffNotificationReply || DEFAULT_CATALOG.staffNotificationReply) + ref;
    const sentResp = await sendTextMessage(wa, customerNumber, text);
    await recordBotAction(biz, customerNumber, text, 'text', sentResp, AI_SENDER);
    // Let staff take it from here: pause the bot for this chat and leave a note saying why.
    await require('./inbox.cjs').pauseForHandover(biz, phone);
    await dbRequest('lead_notes', { method: 'POST', prefer: 'return=minimal', body: { business_id: biz, phone, author: 'AI assistant', body: `🤖 Handed over to the team: ${result.reason}` } });
    await dbRequest('contact_events', { method: 'POST', prefer: 'return=minimal', body: { business_id: biz, phone, event_type: 'ai_handover', data: { reason: result.reason } } });
    await require('./limits.cjs').addUsage(biz, 'aiReplies', 1);
    return true;
  }
  if (result.skip && !['auto-reply is off', 'not configured', 'plan has no AI', 'AI reply limit reached'].includes(result.reason)) console.warn('[AI] skipped:', result.reason);
  return false;
}

/**
 * Record a bot reply in the live chat and Supabase (or surface the Meta error).
 * @param {string} biz @param {string} recipientNumber @param {string} actionDescription @param {string} type
 * @param {MetaSendResult | null | undefined} metaResp @param {string} [senderName]
 */
async function recordBotAction(biz, recipientNumber, actionDescription, type, metaResp, senderName = 'Bot 🤖') {
  requireBusinessId(biz);
  const cleanNumber = cleanPhone(recipientNumber);
  const wa = await whatsappFor(biz, cleanNumber);
  const waNumber = wa?.phoneNumber || '';
  const numberId = wa?.phoneNumberId || null;

  if (metaResp?.error) {
    console.error(`[Meta API Delivery Failed] to ${cleanNumber}:`, metaResp.error);
    const errItem = {
      id: 'err_' + Date.now(),
      direction: 'outbound',
      sender: waNumber,
      senderName: 'Bot System Warning ⚠️',
      recipient: cleanNumber,
      body: `[⚠️ Meta Delivery Error: ${metaResp.error.message || 'Payload validation error'}]`,
      type: 'error',
      timestamp: new Date().toISOString(),
      deliveryStatus: 'failed',
      metaResponse: metaResp,
      numberId,
    };
    pushMessage(errItem, biz);
    broadcastEvent('message', errItem, biz);
    await logMessage(biz, errItem);
    return;
  }

  const isPlain = type === 'text';
  const displayBody = isPlain ? actionDescription : `[🤖 Bot Sent: ${actionDescription}]`;

  const botMsgItem = {
    id: metaResp?.messages?.[0]?.id || 'bot_act_' + Date.now(),
    direction: 'outbound',
    sender: waNumber,
    senderName,
    recipient: cleanNumber,
    body: displayBody,
    type: type || 'interactive',
    timestamp: new Date().toISOString(),
    deliveryStatus: 'sent',
    metaResponse: metaResp,
    numberId,
  };

  pushMessage(botMsgItem, biz);
  broadcastEvent('message', botMsgItem, biz);
  await logMessage(biz, botMsgItem);
  await logLead(biz, cleanNumber, null, displayBody);
}

