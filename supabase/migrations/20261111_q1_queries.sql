-- 2. Categories (per business; separate lists for customer and team queries) -------
create table if not exists public.query_categories (
  id           bigint generated by default as identity primary key,
  business_id  uuid not null references public.businesses(id) on delete cascade,
  kind         text not null check (kind in ('customer', 'internal')),
  name         text not null check (char_length(name) between 1 and 40),
  sort_order   int not null default 0,
  is_active    boolean not null default true,
  unique (business_id, kind, name)
);

-- Default categories for a business (used for existing businesses now, and by the server for new ones).
create or replace function public.seed_query_categories(p_business uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_industry text;
  v_customer text[];
  v_internal text[] := array['How do I…?', 'App problem / bug', 'Access or permission', 'Approval needed', 'Customer escalation', 'Plan / limits', 'Other'];
  i int;
begin
  select industry into v_industry from public.businesses where id = p_business;
  v_customer := case v_industry
    when 'hospital' then array['Appointment', 'Reports', 'Billing', 'Doctor / treatment', 'Complaint', 'Other']
    when 'food'     then array['Order', 'Delivery', 'Payment / refund', 'Quality', 'Complaint', 'Other']
    when 'retail'   then array['Order', 'Delivery', 'Return / exchange', 'Payment / refund', 'Complaint', 'Other']
    else                 array['Booking / appointment', 'Order', 'Billing / payment', 'Service', 'Complaint', 'Other']
  end;
  for i in 1 .. array_length(v_customer, 1) loop
    insert into public.query_categories (business_id, kind, name, sort_order)
    values (p_business, 'customer', v_customer[i], i) on conflict (business_id, kind, name) do nothing;
  end loop;
  for i in 1 .. array_length(v_internal, 1) loop
    insert into public.query_categories (business_id, kind, name, sort_order)
    values (p_business, 'internal', v_internal[i], i) on conflict (business_id, kind, name) do nothing;
  end loop;
end;
$$;

do $$
declare b record;
begin
  for b in select id from public.businesses loop
    perform public.seed_query_categories(b.id);
  end loop;
end $$;

-- 3. Query numbers: Q-1001, Q-1002… per business, without gaps -----------------------
create table if not exists public.query_counters (
  business_id  uuid primary key references public.businesses(id) on delete cascade,
  last_number  int not null default 1000
);

create or replace function public.next_query_number(p_business uuid)
returns int
language sql
security definer
set search_path = public
as $$
  insert into public.query_counters (business_id, last_number) values (p_business, 1001)
  on conflict (business_id) do update set last_number = public.query_counters.last_number + 1
  returning last_number;
$$;

-- 4. Customer and team queries ----------------------------------------------------
create table if not exists public.queries (
  id                 uuid primary key default gen_random_uuid(),
  business_id        uuid not null references public.businesses(id) on delete cascade,
  number             int not null,
  kind               text not null check (kind in ('customer', 'internal')),
  -- customer: bot | ai | staff (raised from a chat); internal: staff
  source             text not null check (source in ('bot', 'ai', 'staff')),
  contact_phone      text,                       -- the customer (customer queries) or a linked chat
  raised_by_email    text,                       -- staff who raised it (null when the customer/AI raised it)
  raised_by_role     text check (raised_by_role in ('owner', 'manager', 'agent')),
  -- who it is for: customer queries = 'team'; team queries = 'managers' or 'owner'
  addressed_to       text not null default 'team' check (addressed_to in ('team', 'managers', 'owner')),
  category           text,
  subject            text not null check (char_length(subject) between 1 and 120),
  description        text check (char_length(description) <= 4000),
  priority           text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  stage              text not null default 'new'
                     check (stage in ('new', 'assigned', 'in_progress', 'waiting', 'escalated', 'resolved', 'closed', 'reopened')),
  assigned_to        text,                       -- staff email
  escalation_level   int not null default 0,
  due_at             timestamptz,
  paused_at          timestamptz,                -- set while 'waiting' (the clock stops)
  first_response_at  timestamptz,
  resolved_at        timestamptz,
  closed_at          timestamptz,
  rating             smallint check (rating between 1 and 5),
  rating_comment     text check (char_length(rating_comment) <= 1000),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  unique (business_id, number),
  constraint queries_customer_has_phone check (kind <> 'customer' or contact_phone is not null),
  constraint queries_internal_raised_by_staff check (kind <> 'internal' or (raised_by_email is not null and addressed_to in ('managers', 'owner'))),
  constraint queries_customer_for_team check (kind <> 'customer' or addressed_to = 'team')
);
create index if not exists queries_business_stage_idx    on public.queries (business_id, stage, created_at desc);
create index if not exists queries_business_assigned_idx on public.queries (business_id, assigned_to);
create index if not exists queries_business_raiser_idx   on public.queries (business_id, raised_by_email);
create index if not exists queries_business_phone_idx    on public.queries (business_id, contact_phone);
create index if not exists queries_due_idx               on public.queries (stage, due_at);

-- Timeline: comments, replies, notes, stage changes...
create table if not exists public.query_events (
  id           bigint generated by default as identity primary key,
  business_id  uuid not null references public.businesses(id) on delete cascade,
  query_id     uuid not null references public.queries(id) on delete cascade,
  author_email text,                              -- staff email, or null for customer/system
  author_role  text,                              -- owner | manager | agent | customer | system
  type         text not null check (type in ('created', 'comment', 'reply', 'note', 'stage', 'assigned', 'priority', 'escalated', 'rating')),
  -- note = handlers only; reply = sent to the customer; comment = visible to everyone who can see the query
  visibility   text not null default 'all' check (visibility in ('all', 'handlers')),
  body         text check (char_length(body) <= 4000),
  data         jsonb not null default '{}'::jsonb,
  created_at   timestamptz not null default now()
);
create index if not exists query_events_query_idx on public.query_events (query_id, created_at);

-- 5. Queries sent to Platform support (any staff role can raise one) ------------------
create sequence if not exists public.platform_query_number_seq start 5001;

create table if not exists public.platform_queries (
  id                 uuid primary key default gen_random_uuid(),
  number             int not null unique default nextval('public.platform_query_number_seq'),
  business_id        uuid not null references public.businesses(id) on delete cascade,
  raised_by_email    text not null,
  raised_by_role     text not null check (raised_by_role in ('owner', 'manager', 'agent')),
  category           text,
  subject            text not null check (char_length(subject) between 1 and 120),
  description        text check (char_length(description) <= 4000),
  priority           text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  stage              text not null default 'new'
                     check (stage in ('new', 'assigned', 'in_progress', 'waiting', 'escalated', 'resolved', 'closed', 'reopened')),
  assigned_to        text,                       -- platform admin email
  escalated_from     uuid references public.queries(id) on delete set null,  -- a team query escalated to the platform
  due_at             timestamptz,
  paused_at          timestamptz,
  first_response_at  timestamptz,
  resolved_at        timestamptz,
  closed_at          timestamptz,
  rating             smallint check (rating between 1 and 5),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create index if not exists platform_queries_stage_idx    on public.platform_queries (stage, created_at desc);
create index if not exists platform_queries_business_idx on public.platform_queries (business_id, created_at desc);

create table if not exists public.platform_query_events (
  id                 bigint generated by default as identity primary key,
  platform_query_id  uuid not null references public.platform_queries(id) on delete cascade,
  business_id        uuid not null references public.businesses(id) on delete cascade,
  author_email       text,
  author_role        text,                       -- owner | manager | agent | platform_admin | system
  type               text not null check (type in ('created', 'comment', 'note', 'stage', 'assigned', 'priority', 'rating')),
  -- note = platform admins only
  visibility         text not null default 'all' check (visibility in ('all', 'platform')),
  body               text check (char_length(body) <= 4000),
  data               jsonb not null default '{}'::jsonb,
  created_at         timestamptz not null default now()
);
create index if not exists platform_query_events_idx on public.platform_query_events (platform_query_id, created_at);

-- 6. Helpers for the rules -----------------------------------------------------------
-- The signed-in staff member's email and role (active business only).
create or replace function public.current_staff_email()
returns text
language sql stable security definer set search_path = public
as $$
  select lower(s.email) from public.staff_members s join public.businesses b on b.id = s.business_id
   where s.user_id = auth.uid() and b.status = 'active';
$$;

create or replace function public.current_staff_role()
returns text
language sql stable security definer set search_path = public
as $$
  select s.role from public.staff_members s join public.businesses b on b.id = s.business_id
   where s.user_id = auth.uid() and b.status = 'active';
$$;

-- 'requester' (raised it) | 'handler' (may work on it) | 'none'. Used by the rules below.
create or replace function public.query_access(p_query uuid)
returns text
language sql stable security definer set search_path = public
as $$
  select case
    when q.business_id is distinct from public.current_business_id() then 'none'
    when public.current_staff_role() = 'owner' then 'handler'
    when q.kind = 'customer' then 'handler'
    when q.addressed_to = 'managers' and public.current_staff_role() = 'manager' then 'handler'
    when lower(q.raised_by_email) = public.current_staff_email() then 'requester'
    else 'none'
  end
  from public.queries q where q.id = p_query;
$$;

revoke all on function public.current_staff_email() from public, anon;
revoke all on function public.current_staff_role() from public, anon;
revoke all on function public.query_access(uuid) from public, anon;
grant execute on function public.current_staff_email() to authenticated;
grant execute on function public.current_staff_role() to authenticated;
grant execute on function public.query_access(uuid) to authenticated;

revoke all on function public.next_query_number(uuid) from public, anon, authenticated;
revoke all on function public.seed_query_categories(uuid) from public, anon, authenticated;
grant execute on function public.next_query_number(uuid) to service_role;
grant execute on function public.seed_query_categories(uuid) to service_role;

-- 7. Rules (RLS): browsers READ only; all changes go through the server ----------------
alter table public.query_categories      enable row level security;
alter table public.query_counters        enable row level security;
alter table public.queries               enable row level security;
alter table public.query_events          enable row level security;
alter table public.platform_queries      enable row level security;
alter table public.platform_query_events enable row level security;

revoke all on public.query_categories, public.query_counters, public.queries, public.query_events,
              public.platform_queries, public.platform_query_events from anon;
revoke insert, update, delete on public.query_categories, public.query_counters, public.queries, public.query_events,
              public.platform_queries, public.platform_query_events from authenticated;
revoke all on public.query_counters from authenticated;   -- no browser access at all

drop policy if exists "business reads categories" on public.query_categories;
create policy "business reads categories" on public.query_categories for select to authenticated
  using (business_id = public.current_business_id());

drop policy if exists "see allowed queries" on public.queries;
create policy "see allowed queries" on public.queries for select to authenticated
  using (public.query_access(id) in ('requester', 'handler'));

-- Handlers see everything on a query they can see; the requester doesn't see handler-only notes.
drop policy if exists "see allowed query events" on public.query_events;
create policy "see allowed query events" on public.query_events for select to authenticated
  using (
    public.query_access(query_id) = 'handler'
    or (public.query_access(query_id) = 'requester' and visibility = 'all')
  );

-- Platform support: the platform admin; or, in the raising business, the raiser and the Business Admin.
drop policy if exists "see platform queries" on public.platform_queries;
create policy "see platform queries" on public.platform_queries for select to authenticated
  using (
    public.is_platform_admin()
    or (business_id = public.current_business_id()
        and (public.current_staff_role() = 'owner' or lower(raised_by_email) = public.current_staff_email()))
  );

drop policy if exists "see platform query events" on public.platform_query_events;
create policy "see platform query events" on public.platform_query_events for select to authenticated
  using (
    public.is_platform_admin()
    or (visibility = 'all' and exists (
          select 1 from public.platform_queries p
           where p.id = platform_query_id
             and p.business_id = public.current_business_id()
             and (public.current_staff_role() = 'owner' or lower(p.raised_by_email) = public.current_staff_email())))
  );

